// Getters
export function getOrders(): Order[] { return [...ordersStore]; }
export function getOrderById(id: string): Order | undefined { return ordersStore.find(o => o.id === id); }
export function getOrdersByCustomerEmail(email: string): Order[] {
  return ordersStore.filter(o => o.customer?.email === email);
}
export function getFulfillments(): Fulfillment[] { return [...fulfillmentsStore]; }
export function getFulfillmentsByOrderId(orderId: string): Fulfillment[] {
  return fulfillmentsStore.filter(f => f.orderId === orderId);
}
export function getReturns(): Return[] { return [...returnsStore]; }
export function getReturnsByOrderId(orderId: string): Return[] {
  return returnsStore.filter(r => r.orderId === orderId);
}

// Mutators
export function createOrder(order: Order): Order {
  ordersStore.push(order);
  return order;
}
export function updateOrder(id: string, updates: Partial<Order>): Order | undefined {
  const idx = ordersStore.findIndex(o => o.id === id);
  if (idx === -1) return undefined;
  ordersStore[idx] = { ...ordersStore[idx], ...updates, updatedAt: new Date().toISOString() };
  return ordersStore[idx];
}
export function createFulfillment(fulfillment: Fulfillment): Fulfillment {
  fulfillmentsStore.push(fulfillment);
  return fulfillment;
}
export function createReturn(ret: Return): Return {
  returnsStore.push(ret);
  return ret;
}
