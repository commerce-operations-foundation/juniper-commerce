export function getProductById(id: string): Product | undefined {
  return products.find(p => p.id === id);
}

export function getVariantsByProductId(productId: string): ProductVariant[] {
  return productVariants.filter(v => v.productId === productId);
}

export function getVariantBySku(sku: string): ProductVariant | undefined {
  return productVariants.find(v => v.sku === sku);
}

export function getCategories(): string[] {
  const cats = new Set<string>();
  products.forEach(p => p.categories?.forEach(c => cats.add(c)));
  return Array.from(cats).sort();
}
